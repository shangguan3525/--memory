import { readdirSync, readFileSync, writeFileSync, statSync } from "node:fs";
import { join, dirname, basename } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const memDir = dirname(here);
const notesDir = join(memDir, "notes");
const REQUIRED = ["type", "status", "created", "source"];
const TYPES = ["fact", "decision", "pref", "pitfall"];
const TYPE_ORDER = { decision: 0, fact: 1, pref: 2, pitfall: 3 };

function parse(text) {
  const m = /^---\r?\n([\s\S]*?)\r?\n---\r?\n?/.exec(text);
  if (!m) return { meta: {}, body: text, hasFm: false };
  const meta = {};
  for (const line of m[1].split(/\r?\n/)) {
    const mm = /^([A-Za-z_][\w-]*)\s*:\s*(.*)$/.exec(line);
    if (!mm) continue;
    let v = mm[2].trim().replace(/^["']|["']$/g, "");
    if (/^\[.*\]$/.test(v)) {
      v = v.slice(1, -1).split(",").map(s => s.trim().replace(/^["']|["']$/g, "")).filter(Boolean);
    }
    meta[mm[1]] = v;
  }
  return { meta, body: text.slice(m[0].length), hasFm: true };
}

function assertionOf(body) {
  for (const raw of body.split(/\r?\n/)) {
    const line = raw.trim();
    if (!line || line.startsWith("#") || line.startsWith(">")) continue;
    const clean = line.replace(/^[-*]\s+/, "").replace(/\*\*/g, "").replace(/`/g, "");
    if (clean) return clean.length > 140 ? clean.slice(0, 137) + "…" : clean;
  }
  return "(缺断言)";
}

const cell = s => String(s == null ? "" : s).replace(/\|/g, "\\|").replace(/\s+/g, " ").trim();
const linkTo = slug => "[[" + slug + "]]";

const entries = [];
const issues = [];
const links = new Map();

for (const f of readdirSync(notesDir)) {
  if (!f.endsWith(".md")) continue;
  const p = join(notesDir, f);
  if (!statSync(p).isFile()) continue;
  const slug = basename(f, ".md");
  const parsed = parse(readFileSync(p, "utf8"));
  const meta = parsed.meta;
  if (!parsed.hasFm) issues.push(slug + "：缺 frontmatter");
  for (const k of REQUIRED) if (!meta[k]) issues.push(slug + "：缺 " + k);
  if (meta.type && !TYPES.includes(meta.type)) issues.push(slug + "：未知 type=" + meta.type);
  if (meta.status && !["active", "superseded"].includes(meta.status)) issues.push(slug + "：未知 status=" + meta.status);
  for (const hit of parsed.body.matchAll(/\[\[([^\]|#]+)/g)) {
    const t = hit[1].trim();
    if (!links.has(t)) links.set(t, []);
    links.get(t).push(slug);
  }
  entries.push({ slug, meta, assertion: assertionOf(parsed.body) });
}

const slugs = new Set(entries.map(e => e.slug));
for (const pair of links) {
  if (!slugs.has(pair[0])) issues.push("断链 [[" + pair[0] + "]] ← " + pair[1].join(", "));
}

const active = entries.filter(e => e.meta.status !== "superseded").sort((a, b) =>
  (TYPE_ORDER[a.meta.type] ?? 9) - (TYPE_ORDER[b.meta.type] ?? 9) ||
  String(b.meta.created).localeCompare(String(a.meta.created)) ||
  a.slug.localeCompare(b.slug));
const superseded = entries.filter(e => e.meta.status === "superseded").sort((a, b) => a.slug.localeCompare(b.slug));

const now = new Intl.DateTimeFormat("sv-SE", { timeZone: "Asia/Shanghai", dateStyle: "short", timeStyle: "short" }).format(new Date());
const HEAD = "| 笔记 | 类型 | 断言 | 创建 | 状态 |\n| --- | --- | --- | --- | --- |";
const row = e => "| " + linkTo(e.slug) + " | " + cell(e.meta.type) + " | " + cell(e.assertion) + " | " + cell(e.meta.created) + " | " + cell(e.meta.status) + " |";

const lines = [];
lines.push("---", "type: meta", "status: active", "created: " + (entries.map(e => e.meta.created).sort()[0] || "1970-01-01"), "source: generated by tools/reindex.mjs — DO NOT EDIT", "tags: [index]", "---", "");
lines.push("# 记忆索引", "");
lines.push("> 生成物，禁止手改：下一次 `bash memory/tools/reindex.sh` 会覆盖。");
lines.push("> 真相在 `notes/*.md` 的 frontmatter。生成于 " + now + "。");
lines.push("> 有效 " + active.length + " 条 / 已取代 " + superseded.length + " 条 / 待修 " + issues.length + " 项。", "");
lines.push("## 有效", "", HEAD);
for (const e of active) lines.push(row(e));
lines.push("");
if (superseded.length) {
  lines.push("## 已取代", "", HEAD);
  for (const e of superseded) lines.push(row(e));
  lines.push("");
}
if (issues.length) {
  lines.push("## 待修");
  for (const i of issues) lines.push("- " + i);
  lines.push("");
}

writeFileSync(join(memDir, "INDEX.md"), lines.join("\n"), "utf8");
console.log("reindex: active=" + active.length + " superseded=" + superseded.length + " issues=" + issues.length);
for (const i of issues) console.log("  ! " + i);
